"""Exploratory paired TESS centroid sensitivity/trade-off follow-up.

Consumes the 248 genuine event pairs generated by the independent, hash-pinned
source runner. Investigates whether lower pointing-drift proxies coincide
with smaller in-event centroid shifts. Neither quantity is ground-truth
planet localization or an incremental ExoMiner accuracy estimate.
"""
import argparse
import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

REQUIRED = (
    "uid", "cohort", "TIC_ID", "orbit_index",
    "prepost_raw_pixels", "prepost_corrected_pixels",
    "event_raw_pixels", "event_corrected_pixels",
)
QUANTITIES = REQUIRED[4:]


def analyze_event_pairs(events, require_frozen=True):
    """Aggregate *within a star first*, avoiding event-level pseudoreplication."""
    missing = sorted(set(REQUIRED) - set(events.columns))
    if missing:
        raise ValueError("Missing original event columns: " + ",".join(missing))
    e = events.copy()
    if e.empty or e[list(REQUIRED[:4])].isna().any().any():
        raise ValueError("Missing source identity or empty original event set")
    if e.duplicated(["uid", "orbit_index"]).any():
        raise ValueError("Repeated source/orbit event cannot count twice")
    for column in QUANTITIES:
        numeric = pd.to_numeric(e[column], errors="coerce")
        if not np.isfinite(numeric.to_numpy(dtype=float)).all() or (numeric < 0).any():
            raise ValueError("Invalid measured original event: " + column)
        e[column] = numeric
    if e.groupby("uid")[["cohort", "TIC_ID"]].nunique().gt(1).any().any():
        raise ValueError("Source UID switched cohort or TIC identity")
    if require_frozen:
        if len(e) != 248 or e.uid.nunique() != 56:
            raise ValueError("Expected 248 original events from 56 original stars")
        if e.groupby("cohort").uid.nunique().to_dict() != {
            "additional_24": 24, "prior_32": 32
        }:
            raise ValueError("Original frozen source-cohort count changed")

    g = e.groupby(["uid", "cohort", "TIC_ID"], sort=True, as_index=False)
    stars = g.agg(
        n_events=("orbit_index", "size"),
        raw_prepost_median=("prepost_raw_pixels", "median"),
        corrected_prepost_median=("prepost_corrected_pixels", "median"),
        raw_event_median=("event_raw_pixels", "median"),
        corrected_event_median=("event_corrected_pixels", "median"),
        raw_prepost_mean=("prepost_raw_pixels", "mean"),
        corrected_prepost_mean=("prepost_corrected_pixels", "mean"),
    )
    stars["pointing_proxy_reduction_pixels"] = (
        stars.raw_prepost_median - stars.corrected_prepost_median
    )
    stars["event_shift_reduction_pixels"] = (
        stars.raw_event_median - stars.corrected_event_median
    )
    stars["pointing_proxy_reduction_using_means_pixels"] = (
        stars.raw_prepost_mean - stars.corrected_prepost_mean
    )
    p = stars.pointing_proxy_reduction_pixels.to_numpy()
    q = stars.event_shift_reduction_pixels.to_numpy()
    p_down = p > 0
    q_down = q > 0
    n = len(stars)

    # Both outcomes are measured on the same stars; no classification labels
    # or additional statistical hypotheses are introduced by this crosstab.
    contingency = {
        "both_pointing_proxy_and_event_shift_reduced": int((p_down & q_down).sum()),
        "pointing_proxy_reduced_event_shift_not_reduced": int((p_down & ~q_down).sum()),
        "pointing_proxy_not_reduced_event_shift_reduced": int((~p_down & q_down).sum()),
        "neither_reduced": int((~p_down & ~q_down).sum()),
        "pointing_proxy_exact_ties": int((p == 0).sum()),
        "event_shift_exact_ties": int((q == 0).sum()),
    }
    assert sum(contingency[k] for k in list(contingency)[:4]) == n

    leave_one_out_medians = [
        float(np.median(np.delete(p, i))) for i in range(n)
    ] if n > 1 else []
    source_mean_changes = stars.pointing_proxy_reduction_using_means_pixels.to_numpy()
    eligible = stars[stars.n_events >= 3]
    cohorts = {}
    for cohort, section in stars.groupby("cohort"):
        x = section.pointing_proxy_reduction_pixels.to_numpy()
        y = section.event_shift_reduction_pixels.to_numpy()
        cohorts[cohort] = {
            "n_stars": len(section),
            "n_event_windows": int(section.n_events.sum()),
            "pointing_proxy_reduced": int((x > 0).sum()),
            "event_shift_reduced": int((y > 0).sum()),
            "both_reduced": int(((x > 0) & (y > 0)).sum()),
            "median_paired_pointing_proxy_reduction_pixels": float(np.median(x)),
        }
    result = {
        "analysis": "post-hoc exploratory sensitivity and same-star trade-off; NOT physical source accuracy",
        "n_star_units": n,
        "n_observed_source_event_windows": len(e),
        "pointing_proxy_reduced_stars": int(p_down.sum()),
        "event_shift_reduced_stars": int(q_down.sum()),
        "joint_star_outcome_counts": contingency,
        "cohort_sensitivity": cohorts,
        "median_of_within_star_paired_proxy_reductions_pixels": float(np.median(p)),
        "alternate_within_star_event_MEAN_aggregation": {
            "reduced_stars": int((source_mean_changes > 0).sum()),
            "increased_stars": int((source_mean_changes < 0).sum()),
            "median_within_star_paired_reduction_pixels": float(np.median(source_mean_changes)),
        },
        "leave_one_STAR_out_sensitivity": {
            "number_of_recomputations": len(leave_one_out_medians),
            "minimum_paired_median_reduction_pixels": min(leave_one_out_medians) if leave_one_out_medians else None,
            "maximum_paired_median_reduction_pixels": max(leave_one_out_medians) if leave_one_out_medians else None,
            "fraction_of_positive_leave_one_out_medians": float(np.mean(np.array(leave_one_out_medians) > 0)) if leave_one_out_medians else None,
        },
        "old_3plus_event_eligibility_subset": {
            "n_stars": len(eligible),
            "pointing_proxy_reduced": int((eligible.pointing_proxy_reduction_pixels > 0).sum()),
            "event_shift_reduced": int((eligible.event_shift_reduction_pixels > 0).sum()),
        },
        "cautions": [
            "The source set was pre-inspected/error-enriched, and this follow-up was selected post hoc.",
            "Smaller in-event centroid displacements could be lower instrumental noise or erased real off-target eclipse signatures; neither is identified here.",
            "These source moment-centroid proxies are not calibrated sky-position truth or the NASA ExoMiner difference-image input.",
            "Repeated transit events from one TIC are NOT independent replicates; all sensitivity uses 56 stars as units.",
            "The unmodified NASA ExoMiner scores were NOT changed, retrained or compared for classification benefit.",
        ],
    }
    return stars, result


def run(input_csv, output_dir):
    path = Path(input_csv)
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    raw = path.read_bytes()
    stars, summary = analyze_event_pairs(pd.read_csv(path), require_frozen=True)
    summary["upstream_paired_event_csv_sha256"] = hashlib.sha256(raw).hexdigest()
    stars.to_csv(out / "56star_pointing_and_event_shift_tradeoff_by_source.csv", index=False)
    (out / "56star_pointing_event_tradeoff_sensitivity.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )

    plt.rcParams.update({"font.family": "serif", "font.size": 10})
    fig, ax = plt.subplots(figsize=(7.0, 5.1))
    for cohort, group in stars.groupby("cohort"):
        ax.scatter(
            1000 * group.pointing_proxy_reduction_pixels,
            1000 * group.event_shift_reduction_pixels,
            alpha=0.8, s=31, marker="s" if cohort == "additional_24" else "o",
            label="Additional 24" if cohort == "additional_24" else "Earlier 32",
        )
    ax.axhline(0, color="grey", lw=0.8)
    ax.axvline(0, color="grey", lw=0.8)
    ax.set(
        xlabel="Raw minus adjusted pre/post movement (millipixels)",
        ylabel="Raw minus adjusted in-event shift (millipixels)",
        title="Paired TESS centroid changes: stability vs. event-shift proxy",
    )
    ax.legend(frameon=False)
    ax.text(
        0.01, 0.01, "Proxy changes only. No claim of improved planet classification.",
        transform=ax.transAxes, ha="left", va="bottom", fontsize=8,
    )
    fig.tight_layout()
    fig.savefig(out / "56star_pointing_vs_event_shift_tradeoff.png", dpi=180)
    plt.close(fig)
    print(json.dumps(summary, indent=2))
    return summary


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--event-pairs", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    run(args.event_pairs, args.out)
